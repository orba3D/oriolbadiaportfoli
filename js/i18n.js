i18next
  .use(i18nextBrowserLanguageDetector)
  .init({
    resources,
    fallbackLng: 'ca',
    supportedLngs: ['ca', 'es', 'en'],
    detection: {
      order: ['localStorage', 'navigator'],
      caches: ['localStorage']
    },
    interpolation: {
      escapeValue: false // permet HTML als textos (com els <span class="highlight">)
    }
  }, function () {
    updateContent();
  });

function updateContent() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.innerHTML = i18next.t(key);
  });

  // Actualitza també els projectes del modal si cal
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.textContent = i18next.t(el.getAttribute('data-i18n-title'));
  });
}

// Funció per canviar d'idioma
window.changeLanguage = function (lang) {
  i18next.changeLanguage(lang, updateContent);

  // Actualitza els botons actius
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
};